// Write work/LIST.md: every Basecamp todo assigned to you and every open issue in a watched repo,
// as links and titles by hub, to pick what to work on.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  compareText,
  isListed,
  issueOrder,
  lower,
  parseGithubId,
  shortRef,
} from "../work-rules.ts";
import type { Data } from "./frontmatter.ts";
import { repoOf } from "./follow.ts";
import { LIST_FILE, list, listWorkFiles, loadWorkFile, text, workOrg } from "./tree.ts";

/** Whether an open item belongs on the list. */
function listed(data: Data, me: Set<string>, watched: Set<string>, org: string): boolean {
  const assigned = list(data.assignees).some((person) => me.has(person));
  const repo = lower(repoOf(text(data.id), org));
  return isListed(
    data.source === "basecamp",
    assigned,
    data.kind === "issue",
    repo !== "" && watched.has(repo),
  );
}

const newestFirst = (a: Data, b: Data) => compareText(text(b.updated), text(a.updated));

/** One part of the list: a heading, then its items by hub, in the given order. */
function part(
  title: string,
  items: Data[],
  order: (a: Data, b: Data) => number,
  org: string,
): string[] {
  if (!items.length) return [];
  const lines = [`## ${title} (${items.length})`, ""];
  for (const hub of [...new Set(items.map((data) => text(data.hub)))].sort()) {
    const inHub = items.filter((data) => data.hub === hub).sort(order);
    lines.push(`### ${hub} (${inHub.length})`, "");
    for (const data of inHub)
      lines.push(`- [${shortRef(text(data.id), org)}](${text(data.url)}) ${text(data.title)}`);
    lines.push("");
  }
  return lines;
}

/** The list, given today's date (YYYY-MM-DD), who you are, and the watched repos. */
function buildList(root: string, today: string, me: string[], watchRepos: string[]): string {
  const org = workOrg(root);
  const meSet = new Set(me);
  const watched = new Set(watchRepos.map(lower));
  const items = listWorkFiles(root)
    .map(loadWorkFile)
    .map((doc) => doc.data)
    .filter((data) => data.type === "item" && data.status === "open")
    .filter((data) => listed(data, meSet, watched, org));
  const basecamp = items.filter((data) => data.source === "basecamp");
  const github = items.filter((data) => data.source !== "basecamp");
  // By repo, then issue number; every listed issue's id parses (`listed` keeps only watched repos)
  const byIssue = (a: Data, b: Data) => {
    const ga = parseGithubId(text(a.id), org);
    const gb = parseGithubId(text(b.id), org);
    return issueOrder(ga.repo, gb.repo, Number(ga.digits), Number(gb.digits));
  };
  return [
    "# Work list",
    "",
    `Generated by \`work summary\` on ${today}: Basecamp todos assigned to you, then open issues in \`watch_repos\`. ${items.length} items.`,
    "",
    ...part("Basecamp todos", basecamp, newestFirst, org),
    ...part("GitHub issues", github, byIssue, org),
  ].join("\n");
}

/** Write work/LIST.md. */
export function writeList(root: string, today: string, me: string[], watchRepos: string[]): void {
  writeFileSync(join(root, LIST_FILE), buildList(root, today, me, watchRepos));
}
