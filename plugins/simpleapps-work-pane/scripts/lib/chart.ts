// Render the work graph as a Mermaid flowchart grouped by hub: work/chart.md and work/chart.html.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  addEdge,
  arrowOf,
  chartLabel,
  chartRef,
  chartTitle,
  htmlText,
  nodeId,
} from "../work-rules.ts";
import type { Graph, Node } from "./tree.ts";
import { CHART_FILE, linkWork, listHubs, text } from "./tree.ts";

const MERMAID_URL = "https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.esm.min.mjs";
const LEGEND =
  "Thick arrow: closes. Dotted arrow: mentions. Blue: GitHub. Green: Basecamp. Generated by `work chart`; do not edit.";

const label = (node: Node) =>
  `${chartLabel(chartRef(node.id))}<br/>${chartLabel(chartTitle(node.title))}`;

/** Unique edges between synced items; `closes` wins over `mention` for the same pair. */
function dependencyEdges(graph: Graph) {
  const known = new Set(graph.nodes.map((node) => node.id));
  let edges = [] as ReturnType<typeof addEdge>;
  for (const edge of graph.edges)
    if (known.has(edge.to)) edges = addEdge(edges, edge.from, edge.to, edge.kind === "closes");
  return edges;
}

/** Mermaid text; `all` keeps items with no links, otherwise only linked items are drawn. */
export function toMermaid(graph: Graph, hubTitles: Map<string, string>, all: boolean) {
  const edges = dependencyEdges(graph);
  const linked = new Set(edges.flatMap((edge) => [edge.from, edge.to]));
  const nodes = graph.nodes.filter((node) => all || linked.has(node.id));
  const lines = ["flowchart LR"];
  for (const hub of [...new Set(nodes.map((node) => node.hub))].sort()) {
    lines.push(`  subgraph ${nodeId(`hub_${hub}`)}["${chartLabel(hubTitles.get(hub) ?? hub)}"]`);
    for (const node of nodes.filter((n) => n.hub === hub))
      lines.push(`    ${nodeId(node.id)}["${label(node)}"]:::${node.source}`);
    lines.push("  end");
  }
  for (const edge of edges)
    lines.push(`  ${nodeId(edge.from)} ${arrowOf(edge.closes)} ${nodeId(edge.to)}`);
  lines.push("  classDef github fill:#eef2ff,stroke:#6366f1");
  lines.push("  classDef basecamp fill:#ecfdf5,stroke:#10b981");
  return { text: `${lines.join("\n")}\n`, nodes: nodes.length, edges: edges.length };
}

function toHtml(mermaidText: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Work chart</title>
<style>body { font-family: system-ui, sans-serif; margin: 16px; background: #fff; color: #111; }</style>
</head>
<body>
<p>${LEGEND}</p>
<pre class="mermaid">
${htmlText(mermaidText)}</pre>
<script type="module">
import mermaid from '${MERMAID_URL}';
mermaid.initialize({ startOnLoad: true, maxTextSize: 1000000, maxEdges: 5000, flowchart: { useMaxWidth: false } });
</script>
</body>
</html>
`;
}

/** Write chart.md (a mermaid block, which IDE Markdown previews render) and chart.html at the root of work/. */
export function writeChart(root: string, all = false) {
  const { graph } = linkWork(root);
  const hubTitles = new Map(listHubs(root).map((hub) => [text(hub.data.id), text(hub.data.title)]));
  const result = toMermaid(graph, hubTitles, all);
  writeFileSync(
    join(root, CHART_FILE),
    `# Work chart\n\n${LEGEND}\n\n\`\`\`mermaid\n${result.text}\`\`\`\n`,
  );
  writeFileSync(join(root, "chart.html"), toHtml(result.text));
  return result;
}
